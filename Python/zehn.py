# Ecrire un Programm Python qui permet de calculer la moyenne de trois entiers saisis par l'utilisateur

zahl1 = int(input("Bitte geben sie der erste Zahl ein: "))
zahl2 = int(input("Bitte geben sie der zweite Zahl ein: "))
zahl3 = int(input("Bitte geben sie der dritte Zahl ein: "))

sum = (zahl1 + zahl2 + zahl3) / 3

print(f"Der Durchschnitt der drei Zahlen ist sum = {sum}")